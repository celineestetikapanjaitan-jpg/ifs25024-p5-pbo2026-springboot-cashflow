package org.delcom.ifs25024springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import java.sql.Statement;

/**
 * Membuat tabel {@code users} dan {@code transactions} bila belum ada.
 * Dijalankan saat aplikasi start dari composition root.
 */
public final class SchemaInitializer {

    static final String CREATE_USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                full_name VARCHAR(200) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )""";

    static final String CREATE_TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )""";

    private SchemaInitializer() {
    }

    /** Membuat seluruh tabel yang dibutuhkan aplikasi. */
    public static void initialize(DataSource dataSource) {
        JdbcSupport.execute(dataSource, connection -> {
            try (Statement statement = connection.createStatement()) {
                statement.execute(CREATE_USERS);
                statement.execute(CREATE_TRANSACTIONS);
            }
            return null;
        });
    }
}
